def test_artifact_ref_model_and_schema_share_the_common_identity_matrix() -> None:
    """A missing common identity field would make a public ref ambiguous."""
    schema = load_artifact_ref_schema()
    common_fields = {
        'artifact_id',
        'logical_output_id',
        'revision',
        'kind',
        'mime_type',
        'custody',
        'state',
        'created_at',
        'effective_retention',
        'producer',
        'supersedes_artifact_id',
    }

    assert common_fields <= set(OrdinaryArtifactRef.model_fields)
    assert common_fields <= set(PrivateArtifactRef.model_fields)
    assert set(EffectiveRetention.model_fields) == {
        'policy_snapshot_id',
        'retention_class',
        'expires_at',
    }
    assert set(ProducerLineage.model_fields) == {
        'producer_class',
        'producer_id',
        'root_invocation_id',
        'session_id',
        'call_id',
        'dispatch_id',
        'attempt_id',
    }
    assert set(PrivateProducerLineage.model_fields) == set(ProducerLineage.model_fields)
    assert set(schema['$defs']['privateProducerLineage']['properties']) == set(
        PrivateProducerLineage.model_fields,
    )
    assert set(ValidationReceipt.model_fields) == {
        'receipt_id',
        'status',
        'validator_profile',
        'validator_version',
    }
    assert set(RetrievalAction.model_fields) == {'relation'}
    assert schema['$schema'] == 'https://json-schema.org/draft/2020-12/schema'
    assert schema['additionalProperties'] is False
    assert set(schema['$defs']['ordinaryArtifactRef']['properties']) == set(
        OrdinaryArtifactRef.model_fields,
    )
    assert set(schema['$defs']['privateArtifactRef']['properties']) == set(
        PrivateArtifactRef.model_fields,
    )
    ordinary_only = {
        'display_filename',
        'size_bytes',
        'sha256',
        'validation_receipt',
        'safe_preview',
        'retrieval_action',
    }
    private_only = {
        'display_label',
        'creation_receipt_id',
        'deletion_receipt_id',
        'retrieval_action',
    }
    assert set(OrdinaryArtifactRef.model_fields) == common_fields | ordinary_only
    assert set(PrivateArtifactRef.model_fields) == common_fields | private_only
